/* 
    Так же есть фундаментальное правило алгоритмов и структур данных, 
    любая рекурсивная функция может быть преобразована в итеративный цикл и наоборот. 
*/
function fib(n) {
  if (n <= 1) return n;

  let a = 0,
    b = 1;

  for (let i = 2; i <= n; i++) {
    let next = a + b;
    a = b;
    b = next;
  }

  return b;
}

console.log(fib(5));

/* 
    Решение данной проблемы с многогратными повторными вычислениями - мемоизация
    Мемоизация — техника оптимизации, при которой результаты дорогих (CPU/время) чистых функций кэшируются по ключу (аргументам). 
    При повторном вызове с тем же ключом возвращается кэш вместо перевычисления.
*/
function memoize(fn) {
  // универсальная функция-обертка, для мемоизации любой функции с произвольными аргументами
  const cache = new Map(); // Создаем кэш внутри замыкания

  return function (...args) {
    // возвращаем новую функцию, которая сохраняет в кэш предыдущие вызовы по аргументам
    // ...args — это синтаксис остаточных (rest) параметров
    const key = JSON.stringify(args);

    if (cache.has(key)) return cache.get(key);

    const result = fn(...args);

    cache.set(key, result);
    console.log(cache);
    return result;
  };
}

// 1. C одним аргументом
const fibonaciMemoized = memoize((n) => (n <= 1 ? n : fib(n - 1) + fib(n - 2)));
fibonaciMemoized(40); // args = [40], key = "[40]"

// 2. С несколькими аргументами
const sumMemoized = memoize((a, b, c) => a + b + c);
sumMemoized(1, 2, 3); // args = [1, 2, 3], key = "[1,2,3]"

// 3. С Любыми аргументами!
const greet = memoize((name, age, city) => `${name} ${age} ${city}`);
greet("Вася", 25, "Москва"); // args = ["Вася", 25, "Москва"]

