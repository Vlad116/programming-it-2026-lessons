// С мемоизацией (линейная сложность O(n))
function fibMemoized(n) {
  // Cпособ 1
  const cache = new Map();

  function fib(n) {
    if (n <= 1) return n;

    const key = n;

    if (cache.has(key)) {
      console.log(`Берется из кэша вызов fib(${key})`);
      return cache.get(key);
    }

    console.log(`Вычисляем fib(${key})`);

    const result = fib(n - 1) + fib(n - 2);
    cache.set(key, result);

    return result;
  }

  return fib;
}

