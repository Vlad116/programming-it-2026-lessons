/*
    Замыкание (closure) - комбинация функции с её лексическим окружением, 
    которое сохраняется даже после выхода из внешней функции.

    Лексическое окружение (Lexical Environment) - это скрытая внутренняя структура, 
    которая хранит соответствие переменных и их значений,
    а также ссылку на внешнее (родительское) окружение.

    Состав окружения:
        - Environment Record (Запись окружения): Объект, в котором хранятся локальные переменные и функции (своеобразный [[Map]] переменных).
        - Ссылка на внешнее окружение: Ссылка на родительский блок кода или функцию.

    Не путать с "областью видимости" (Scope) - https://doka.guide/js/closures/

    Область видимости (Scope)
        - Зона кода, где переменная доступна. Определяется структурой кода (где объявлена).
    
    Лексическое окружение (Lexical Environment)
        - Внутренняя структура данных JS-движка. Объект со списком переменных + ссылкой на внешнее окружение.
*/

function makeCounter() {
  let count = 0; // Пример реализации "инкапсуляции" в js, напрямую не можем изменять значение переменно из вне, только вызывая функцию

  return function () {
    /*
       ++count префиксный инкремент, count = count + 1 || count += 1
       Префиксный ++x = "сначала +1, потом используй значение"
       Постфиксный x++ = "сначала используй значение, потом +1", аналогично с декрементом для --x / x--
    */
    return ++count;
  };
}

