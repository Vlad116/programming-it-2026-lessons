/*
    Рекурсия — это техника, при которой функция вызывает саму себя для решения исходной задачи 
    путём разбиения на более мелкие подзадачи одного и того же типа.
    Это математически элегантный подход, основанный на принципе "разделяй и властвуй" из теории алгоритмов.

    Полная структура рекурсивной функции:

    1. Базовый случай (base case) — тривиальное решение без рекурсии. Обязателен! Без него — бесконечный цикл и stack overflow.

    2. Рекурсивный случай (recursive step) — приближение к базе + рекурсивный вызов.

    3. Гарантия завершения — каждый вызов должен уменьшать размер проблемы.

    Жизненный пример: Поиск файла на диске во вложенной файловой структуре. 
    "Если это нужный файл — возврати. Иначе: проверь содержимое папки рекурсивно."
*/

function fibRecursive(n) {
  if (n <= 1) return n; // Базовый случай - обязательно должен существовать, иначе будет аналог бесконечного цикла

  const result = fibRecursive(n - 1) + fibRecursive(n - 2);
  console.log(result);
  return result;
}

